def train_model(model_name: str, src: str, tgt: str, num_train=10, num_test=10, num_val=10):
    need_prompt = model_name.startswith('t5')
    data = load_dataset("wmt17", name="-".join([src, tgt]), split="train", cache_dir='./cache')

    lang_src = lang_map[src]
    lang_tgt = lang_map[tgt]
    tok, model = build_model(model_name, lang_src, lang_tgt)

    num_train_epochs = 10
    max_src, max_tgt = 128, 128

    def compute_metrics(eval_preds):
        preds, labels = eval_preds

        # --- FIX: Prevent OverflowError during decoding ---
        # The OverflowError happens when token IDs in 'preds' are extremely large 
        # (e.g., garbage values generated by an unstable model) and exceed the 
        # integer capacity of the fast tokenizer's decode function.
        
        # 1. Ensure preds is a numpy array and get vocabulary size
        if hasattr(preds, 'cpu'):
             # Convert tensor to numpy array if it hasn't been already
             preds = preds.cpu().numpy()
             
        max_valid_id = len(tok)
        
        # 2. Identify tokens that are out of the valid range [0, max_valid_id - 1]
        # and replace them with the pad token ID.
        # This cleans up large/negative invalid IDs before the fast tokenizer attempts conversion.
        preds = np.where((preds >= max_valid_id) | (preds < 0), tok.pad_token_id, preds)
        
        # --- Original Labels cleaning (required for Seq2Seq) ---
        labels = np.where(labels != -100, labels, tok.pad_token_id)
        
        # Decoding now happens with safe token IDs
        pred_str = tok.batch_decode(preds, skip_special_tokens=True)
        label_str = tok.batch_decode(labels, skip_special_tokens=True)

        bleu_score  = bleu.compute(predictions=pred_str,
                                     references=[[r] for r in label_str])["score"]
        chrf_score  = chrf.compute(predictions=pred_str,
                                     references=label_str)["score"]

        return {"bleu": bleu_score, "chrf": chrf_score}

    def encode(ex):
        # Using clearer variable names: src_text (Chinese) and tgt_text (English)
        src_text = [item[src] for item in ex["translation"]] # Source (Chinese)
        tgt_text = [item[tgt] for item in ex["translation"]] # Target (English)
        
        if need_prompt:
            # FIX 1: T5 requires the prompt to be prepended to the SOURCE text (Encoder Input).
            # The label (text_target) should remain the clean target text.
            src_text = [f"translate Chinese to English: " + item for item in src_text]

        # Tokenize the prompted source text and the clean target text (labels)
        model_inputs = tok(
            src_text,
            text_target=tgt_text,
            max_length=max_src,
            truncation=True,
            padding=False,          # 动态 padding，由 data_collator 完成
        )
        return model_inputs

    raw_train, raw_test, raw_val = split_train_test(data,
                                                    num_trains=num_train, num_test=num_test, num_val=num_val)
    # Why we tokenize the split instead of data? Since data is very large, and we only use a small part of it!!
    # So 3 times tokenizations is OK.
    tokenised_train = raw_train.map(encode, batched=True)
    tokenised_val = raw_val.map(encode, batched=True)
    tokenised_test = raw_test.map(encode, batched=True)

    data_coll = DataCollatorForSeq2Seq(tok, model=model)

    args = Seq2SeqTrainingArguments(
        # output_dir='/content/output',
        eval_strategy="steps",
        eval_steps=500,
        logging_steps=100,
        save_steps=500,
        per_device_train_batch_size=4,
        per_device_eval_batch_size=4,
        gradient_accumulation_steps=4,
        learning_rate=3e-5,
        num_train_epochs=num_train_epochs,
        predict_with_generate=True,
        generation_max_length=max_tgt,
        save_total_limit=2,
        load_best_model_at_end=True,
        metric_for_best_model="bleu",
        greater_is_better=True,
        report_to="none",
        fp16=True,
    )

    trainer = Seq2SeqTrainer(
        model=model,
        args=args,
        train_dataset=tokenised_train,
        eval_dataset=tokenised_val,
        processing_class=tok,
        data_collator=data_coll,
        compute_metrics=compute_metrics,
        callbacks=[EarlyStoppingCallback(early_stopping_patience=2)],
    )
    # trainer.train()
    return model, tok


