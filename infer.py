import torch
from tqdm.auto import tqdm

def translate(model, tok, input_data, need_prompt=True):
    model.eval()
    device = get_avail_device()

    # 1. 生成参数（可按需调）
    gen_kwargs = {
        "max_length": 64,
        "num_beams": 4,
        "early_stopping": True,
    }

    out_f = []

    for sample in tqdm(input_data, desc="Translating"):
        raw_src_text = sample["translation"][src]
        
        if need_prompt:
            # FIX 2: Prepend the T5 task prompt to the source sentence for inference.
            prompted_src_text = f"translate Chinese to English: {raw_src_text}"
            
        inputs = tok(prompted_src_text, return_tensors="pt").to(device)

        with torch.no_grad():
            pred = model.generate(**inputs, **gen_kwargs)

        hyp = tok.decode(pred[0], skip_special_tokens=True)
        out_f.append(hyp.strip())

    return out_f


